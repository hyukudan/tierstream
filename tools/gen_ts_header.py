#!/usr/bin/env python3
"""Generates the tierstream names of the C ABI from include/strix_stream/ss.h (design notes §2.1).

For this release the strix-stream names stay the real ones: ss.h is never edited by this tool, the ss_* functions keep
their definitions, and the outputs only ADD names:
  include/tierstream/ts.h   typedef names, TS_* macros for the enum constants and macros, TS_API declarations of the
                            ts_* functions, static inline wrappers of the inline helpers (qualifiers and #if guards
                            kept: ss_dg_slot gives a __device__ ts_dg_slot under __CUDACC__)
  src/ts_api.cpp            the ts_* exports, each a one-line call of its ss_* function
  tests/ts_pairs.inc        TS_FN_PAIR(name) / TS_TYPE_PAIR(name) for the compatibility tests
Usage: gen_ts_header.py [--check]   (--check: fail when a generated file differs from what is checked in)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SS_H = ROOT / "include" / "strix_stream" / "ss.h"
TS_H = ROOT / "include" / "tierstream" / "ts.h"
TS_CPP = ROOT / "src" / "ts_api.cpp"
PAIRS = ROOT / "tests" / "ts_pairs.inc"


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", lambda m: "\n" * m.group(0).count("\n"), text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def split_args(args):
    args = args.strip()
    if args in ("", "void"):
        return []
    out, depth, cur = [], 0, ""
    for ch in args:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    out.append(cur.strip())
    return out


def arg_name(arg):
    m = re.search(r"\(\s*\*\s*(\w+)\s*\)", arg)  # function pointer
    if m:
        return m.group(1)
    m = re.search(r"(\w+)\s*(\[[^\]]*\])?\s*$", arg)
    if not m:
        raise SystemExit("gen_ts_header: cannot name the argument '%s'" % arg)
    return m.group(1)


def norm(s):
    return re.sub(r"\s+", " ", s).strip()


def parse(text):
    code = strip_comments(text)
    fns = []  # (ret, name, args)
    for m in re.finditer(r"\bSS_API\s+([^;{}]*?)\b(ss_\w+)\s*\(([^;{}]*?)\)\s*;", code, flags=re.S):
        fns.append((norm(m.group(1)), m.group(2), norm(m.group(3))))
    # static inline helpers, with the #if guard around them (if any)
    inlines = []  # (qualifiers + ret, name, args, guard or None)
    guard = None
    lines = code.split("\n")
    i = 0
    while i < len(lines):
        line = lines[i]
        g = re.match(r"\s*#\s*if\s+(.*)$", line)
        if g:
            guard = g.group(1).strip()
        if re.match(r"\s*#\s*endif", line):
            guard = None
        m = re.match(r"\s*static\s+((?:__device__\s+|__host__\s+|__forceinline__\s+|inline\s+)*)([^()]*?)\b(ss_\w+)\s*\(([^)]*)\)\s*\{", line)
        if m:
            quals = norm(m.group(1))
            ret = norm(m.group(2))
            inlines.append((quals, ret, m.group(3), norm(m.group(4)), guard))
        i += 1
    types = sorted(set(re.findall(r"\}\s*(ss_\w+)\s*;", code)) |
                   set(re.findall(r"\btypedef\s+(?:struct|enum)\s+\w+\s+(ss_\w+)\s*;", code)) |
                   set(re.findall(r"\btypedef\s+[^;]*?\(\s*\*\s*(ss_\w+)\s*\)", code)))
    consts = set()
    for body in re.findall(r"\benum\s+\w*\s*\{([^}]*)\}", code, flags=re.S):
        for name in re.findall(r"\b(SS_\w+)\s*(?:=|,|$)", body):
            consts.add(name)
    macros = set(re.findall(r"^\s*#\s*define\s+(SS_\w+)(?!\()", text, flags=re.M))
    macros.discard("SS_H")
    return fns, inlines, types, sorted(consts), sorted(macros)


def ts(name):
    assert name.startswith("ss_") or name.startswith("SS_"), name
    return ("ts_" if name.startswith("ss_") else "TS_") + name[3:]


def generate():
    text = SS_H.read_text(encoding="utf-8")
    fns, inlines, types, consts, macros = parse(text)
    h = []
    h.append("/* tierstream C ABI: the new names of include/strix_stream/ss.h. GENERATED by tools/gen_ts_header.py from ss.h")
    h.append(" * (a CTest regenerates and compares it): do not edit.")
    h.append(" *")
    h.append(" * strix-stream was renamed tierstream. For one release the strix-stream names (ss_*, SS_*) stay the real")
    h.append(" * definitions, so existing code builds and links unchanged; this header adds the tierstream names for the same")
    h.append(" * functions, types and constants: typedef names, TS_* macros, real exported ts_* functions (each calls its ss_*")
    h.append(" * function) and inline wrappers. Types are the same types: a ts_budget* is an ss_budget*. */")
    h.append("#ifndef TIERSTREAM_TS_H")
    h.append("#define TIERSTREAM_TS_H")
    h.append("")
    h.append('#include "../strix_stream/ss.h"')
    h.append("")
    h.append("#define TS_API SS_API")
    h.append("")
    h.append("/* types */")
    for t in types:
        h.append("typedef %s %s;" % (t, ts(t)))
    h.append("")
    h.append("/* enum constants and macros */")
    for c in consts + [m for m in macros if m not in consts and m not in ("SS_API",)]:
        h.append("#define %s %s" % (ts(c), c))
    h.append("")
    h.append("#ifdef __cplusplus")
    h.append('extern "C" {')
    h.append("#endif")
    h.append("")
    h.append("/* functions */")
    for ret, name, args in fns:
        h.append("TS_API %s %s(%s);" % (ret, ts(name), args if args else "void"))
    h.append("")
    open_guard = None
    for quals, ret, name, args, guard in inlines:
        if guard != open_guard:
            if open_guard:
                h.append("#endif")
            if guard:
                h.append("#if %s" % guard)
            open_guard = guard
        names = ", ".join(arg_name(a) for a in split_args(args))
        call = "%s(%s)" % (name, names)
        body = ("%s;" % call) if ret == "void" else ("return %s;" % call)
        qual = ("static " + quals + " ") if quals else "static inline "
        h.append("%s%s %s(%s) { %s }" % (qual, ret, ts(name), args if args else "void", body))
    if open_guard:
        h.append("#endif")
    h.append("")
    h.append("#ifdef __cplusplus")
    h.append("}")
    h.append("#endif")
    h.append("")
    h.append("#endif /* TIERSTREAM_TS_H */")
    header = "\n".join(h) + "\n"

    c = []
    c.append("// The tierstream exports (include/tierstream/ts.h). GENERATED by tools/gen_ts_header.py: do not edit.")
    c.append("// Each calls its strix-stream function, which stays the real definition for this release.")
    c.append('#include "tierstream/ts.h"')
    c.append("")
    c.append('extern "C" {')
    c.append("")
    for ret, name, args in fns:
        names = ", ".join(arg_name(a) for a in split_args(args))
        call = "%s(%s)" % (name, names)
        body = ("%s;" % call) if ret == "void" else ("return %s;" % call)
        c.append("%s %s(%s) { %s }" % (ret, ts(name), args if args else "void", body))
    c.append("")
    c.append('}  // extern "C"')
    source = "\n".join(c) + "\n"

    p = ["// Old / new name pairs for the compatibility tests. GENERATED by tools/gen_ts_header.py: do not edit."]
    for _, name, _ in fns:
        p.append("TS_FN_PAIR(%s)" % name[3:])
    for t in types:
        p.append("TS_TYPE_PAIR(%s)" % t[3:])
    pairs = "\n".join(p) + "\n"
    return {TS_H: header, TS_CPP: source, PAIRS: pairs}


def main():
    out = generate()
    if "--check" in sys.argv[1:]:
        bad = [str(path.relative_to(ROOT)) for path, text in out.items()
               if not path.exists() or path.read_text(encoding="utf-8") != text]
        if bad:
            print("gen_ts_header: out of date (run tools/gen_ts_header.py): " + ", ".join(bad))
            return 1
        print("gen_ts_header: up to date")
        return 0
    for path, text in out.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote " + str(path.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
